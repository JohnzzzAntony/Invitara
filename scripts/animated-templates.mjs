// Prepares frontend/public/invitation-templates for the editor. Run after adding or changing a template:
//   node scripts/animated-templates.mjs
// 1. Adds the edit.js runtime before each template's own scripts.
// 2. Runs edit.js's field walk in Chromium (template scripts removed) and writes js/animated-data.js,
//    the schema the editor, server validation and pricing use.
import {chromium} from '@playwright/test';
import {readFileSync,writeFileSync} from 'node:fs';

const dir=new URL('../frontend/public/invitation-templates/',import.meta.url);
const tag='<script src="../edit.js"></script>\n';
const editJs=readFileSync(new URL('edit.js',dir),'utf8');
const manifest=JSON.parse(readFileSync(new URL('manifest.json',dir),'utf8'));
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage();
await page.route('**/*',route=>route.abort());
const out=[];
for(const t of manifest.templates){
  const file=new URL(t.path,dir);
  let html=readFileSync(file,'utf8');
  if(!html.includes(tag)){
    const at=html.indexOf('<script',html.indexOf('<body'));
    if(at<0)throw new Error(t.id+': no template script found');
    html=html.slice(0,at)+tag+html.slice(at);writeFileSync(file,html);
  }
  await page.setContent(html.replace(/<script\b[\s\S]*?<\/script>/g,''));
  await page.addScriptTag({content:editJs});
  const fields=await page.evaluate(()=>window.INVITE_FIELDS(document).map(f=>[f.section,f.key,f.text]));
  if(!fields.some(f=>f[0]==='rsvp'))throw new Error(t.id+': guest replies need a section with id="rsvp"');
  out.push({id:t.id,path:t.path,design:t.design,occasion:t.occasion,intro:t.intro,motion:t.motion,themeColor:t.themeColor,date:t.event.date,title:t.event.title,venue:t.event.venue,fields});
}
await browser.close();
writeFileSync(new URL('../frontend/public/js/animated-data.js',import.meta.url),'/* Generated by scripts/animated-templates.mjs from invitation-templates. Do not edit. */\nwindow.INVITARA_ANIMATED='+JSON.stringify(out)+';\n');
console.log('Prepared '+out.length+' animated templates: '+out.map(t=>t.fields.length).join(', ')+' editable texts.');
